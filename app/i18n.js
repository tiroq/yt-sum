export function isSupportedUiLanguage(language) {
  return SUPPORTED_UI_LANGUAGES.includes(language);
}

export function createUiDictionary(language = DEFAULT_UI_LANGUAGE) {
  const normalized = isSupportedUiLanguage(language) ? language : DEFAULT_UI_LANGUAGE;
  return UI_TEXT[normalized];
}

export function getUiText(language, key, fallback = key) {
  const dictionary = createUiDictionary(language);
  return dictionary[key] ?? UI_TEXT[DEFAULT_UI_LANGUAGE][key] ?? fallback;
}
